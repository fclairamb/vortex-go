#!/usr/bin/env bash
# Writes internal/edition/table.go from upstream's vortex-edition/src/declarations/core/*.rs
# at tag <version>. Set VORTEX_SRC to a local clone (already at that tag) to skip the network.
# Usage: scripts/edition.sh [version]   (defaults to .vortex-version)
set -euo pipefail

root="$(cd "$(dirname "$0")/.." && pwd)"
version="${1:-$(tr -d '[:space:]' < "$root/.vortex-version")}"
rel="vortex-edition/src/declarations/core"
raw="https://raw.githubusercontent.com/vortex-data/vortex/${version}/${rel}"

fetch() {
  if [ -n "${VORTEX_SRC:-}" ]; then cat "$VORTEX_SRC/$rel/$1"; else curl -fsSL "$raw/$1"; fi
}

files="$(fetch mod.rs | sed -n 's/^pub mod \(.*\);/\1/p')"
tmp="$(mktemp)"
trap 'rm -f "$tmp"' EXIT
for f in $files; do
  fetch "$f.rs" | grep -v '^[[:space:]]*//' | awk '
    /^[[:space:]]*id: CORE_/ { id = $2; sub(/,$/, "", id); sub(/^CORE_/, "", id) }
    /min_library_version: Some\(/ { m = $0; sub(/.*Some\("/, "", m); sub(/".*/, "", m); min = m }
    {
      line = $0
      while (match(line, /EditionMember::[a-z]+\(&"[^"]+"\)/)) {
        s = substr(line, RSTART, RLENGTH)
        kind = s; sub(/EditionMember::/, "", kind); sub(/\(.*/, "", kind)
        mid = s; sub(/.*&"/, "", mid); sub(/".*/, "", mid)
        print id, min, kind, mid
        line = substr(line, RSTART + RLENGTH)
      }
    }'
done > "$tmp"

# Newest edition whose min_library_version is at most the pinned release.
newest="$(awk -v v="$version" '
  function num(s,   a, n) { n = split(s, a, "."); return a[1] * 1000000 + a[2] * 1000 + a[3] }
  num($2) <= num(v) { split($1, p, "_"); k = p[1] * 1000000 + p[2] * 1000 + p[3]; if (k > best) { best = k; id = $1 } }
  END { print id }' "$tmp")"
[ -n "$newest" ] || { echo "no core edition supports $version" >&2; exit 1; }
nk="$(echo "$newest" | awk -F_ '{ print $1 * 1000000 + $2 * 1000 + $3 }')"
display="core $(echo "$newest" | awk -F_ '{ printf "%s.%s.%s", $1, $2, $3 }')"

out="$root/internal/edition/table.go"
{
  echo "// Code generated by scripts/edition.sh from upstream $version; DO NOT EDIT."
  echo
  echo "package edition"
  echo
  echo "// Version is the upstream release the table was generated from."
  echo "const Version = \"$version\""
  echo
  echo "// ID is the newest core edition the release supports."
  echo "const ID = \"$display\""
  echo
  echo "var members = []Member{"
  awk -v nk="$nk" '
    { split($1, p, "_"); k = p[1] * 1000000 + p[2] * 1000 + p[3]
      if (k <= nk) printf "\t{Kind: \"%s\", ID: \"%s\", Since: \"core %s.%s.%s\"},\n", $3, $4, p[1], p[2], p[3] }' "$tmp" \
    | sort -t'"' -k2,2 -k4,4
  echo "}"
} > "$out"
gofmt -w "$out"
echo "edition $version: $display"
